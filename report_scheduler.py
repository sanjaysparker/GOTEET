"""GOTEET-owned local schedules. No Codex/Claude jobs or external-agent execution."""
import datetime as dt
import json
import threading
import time
import uuid
import logging
import engine
import insights
import settings
import work
from collector import IST, now

LOCK = threading.Lock()
STOP = threading.Event()
THREAD = None
LOG = logging.getLogger('goteet.scheduler')

def slots(at):
    at = at.astimezone(IST)
    daily = at.replace(hour=9, minute=0, second=0, microsecond=0)
    if daily > at: daily -= dt.timedelta(days=1)
    weekly = at.replace(hour=18, minute=0, second=0, microsecond=0) - dt.timedelta(days=(at.weekday()-4)%7)
    if weekly > at: weekly -= dt.timedelta(days=7)
    analysis = at.replace(minute=(at.minute//30)*30, second=0, microsecond=0)
    return {'daily':daily.isoformat(), 'weekly':weekly.isoformat(), 'analysis':analysis.isoformat()}

def _ensure(c):
    c.execute('CREATE TABLE IF NOT EXISTS report_schedule(kind TEXT PRIMARY KEY, slot TEXT NOT NULL, completed_at TEXT NOT NULL, error TEXT NOT NULL)')

def status():
    with engine.connect() as c:
        _ensure(c)
        rows=[dict(r) for r in c.execute('SELECT * FROM report_schedule')]
    return {'enabled':settings.get()['auto_analysis'], 'timezone':'Asia/Kolkata',
            'daily':'09:00', 'weekly':'Friday 18:00', 'analysis':'Every 30 minutes',
            'runs':rows,'runtime':'While GOTEET is open; latest missed run catches up after launch.',
            'engine':'Local evidence analysis; no external agent invoked.'}

def analyse_local():
    result=insights.analyse()
    summary='\n'.join(['GOTEET automatic evidence analysis',
        f"{result['totals']['open']} open tasks · {result['counts']['critical']} critical findings", *[
        f"{f['title']} — {f['detail']} Recommendation: {f['suggestion']}" for f in result['findings'][:12]]])
    prefs=settings.get()
    if prefs.get('analysis_provider')=='ollama' and prefs.get('analysis_model'):
        try:
            result_ai=insights.run('ollama',prefs['analysis_model'],'Automatic project review. Observed evidence only; propose updates for review, never apply them.')
            work.notify('analysis','Automatic AI project review',result_ai['analysis']['summary'][:1200], 'analysis',result_ai['analysis']['id'],'goteet-scheduler')
            return
        except Exception as error:
            summary+='\nLocal AI unavailable ('+type(error).__name__+'); evidence analysis retained.'
    c=insights._store()
    try:
        ident=str(uuid.uuid4())
        c.execute('INSERT INTO analyses VALUES(?,?,?,?,?,?,?)',(ident,now(),'goteet-local',result['score'],summary,'',json.dumps(result['counts'])))
        c.commit()
    finally:c.close()
    work.notify('analysis','Automatic work analysis',summary[:1200],'analysis',ident,'goteet-scheduler')

def tick(clock=None):
    if not settings.get()['auto_analysis'] or not LOCK.acquire(blocking=False):return
    try:
        desired=slots(clock or dt.datetime.now(IST))
        with engine.connect() as c:
            _ensure(c)
            previous={r['kind']:dict(r) for r in c.execute('SELECT * FROM report_schedule')}
        due=[kind for kind,slot in desired.items() if previous.get(kind,{}).get('slot')!=slot or previous.get(kind,{}).get('error')]
        if not due:return
        refresh_errors=[]
        try:
            prefs=settings.get()
            if prefs['github_enabled'] or prefs['local_index_enabled']:engine.collect()
        except Exception as e:refresh_errors.append('GitHub/local refresh failed: '+type(e).__name__)
        try:
            import google_auth
            if settings.get()['google_enabled']:
                connection=google_auth.status()
                selected=[k for k in ('gmail','drive','calendar') if connection.get('sources',{}).get(k)]
                if connection.get('connected') and selected:google_auth.sync(selected)
        except Exception as e:refresh_errors.append('Google refresh failed: '+type(e).__name__)
        import agent_observer
        agent_observer.safe_scan()
        for kind in due:
            error=''
            try:
                if kind=='analysis':analyse_local()
                else:
                    report=engine.report(kind)
                    work.notify('report',f'{kind.title()} review ready',
                        'Generated by GOTEET. '+(' '.join(refresh_errors) if refresh_errors else 'Source capture times and coverage are included.'),
                        'report',report['id'],'goteet-scheduler')
            except Exception as e:
                error=type(e).__name__;LOG.warning('Scheduled %s failed: %s',kind,error)
            with engine.connect() as c:
                c.execute('INSERT OR REPLACE INTO report_schedule VALUES(?,?,?,?)',(kind,desired[kind],now(),error))
    finally:LOCK.release()

def start():
    global THREAD
    if THREAD and THREAD.is_alive():return
    STOP.clear()
    def loop():
        while not STOP.wait(60):
            try:tick()
            except Exception as e:LOG.warning('Scheduler failed: %s',type(e).__name__)
    THREAD=threading.Thread(target=loop,name='goteet-reports',daemon=True);THREAD.start()
